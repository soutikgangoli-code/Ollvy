// Single source of truth for email templates.
//
// The Node (Next.js) app and the Deno (Supabase edge functions) runtime each
// need the templates, but can't share a module (different import rules). So the
// Node templates in apps/customer/lib/email/templates/ are the SOURCE, and this
// script generates the Deno copies in supabase/functions/_shared/email-templates/.
//
// The only difference between the two is that Deno requires explicit `.ts`
// extensions on relative imports — that's the only transform applied.
//
// Usage:
//   node scripts/sync-email-templates.mjs           # regenerate the Deno copies
//   node scripts/sync-email-templates.mjs --check    # exit 1 if they are stale (CI)
//
// NOT synced:
//   - order-completed.ts : sent only from a Next.js admin action (Node-only).
//   - format.ts          : genuinely runtime-specific (Node re-exports from
//                          @/lib/utils; Deno has its own implementation).

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'apps/customer/lib/email/templates');
const DST = join(ROOT, 'supabase/functions/_shared/email-templates');

// Templates shared by both runtimes (order-completed.ts is intentionally absent).
const FILES = [
  'shared-layout.ts',
  'payment-confirmation.ts',
  'submission-complete.ts',
  'incomplete-order-reminder.ts',
  'admin-update.ts',
];

function banner(name) {
  return (
    `// AUTO-GENERATED from apps/customer/lib/email/templates/${name}\n` +
    `// by scripts/sync-email-templates.mjs. Do NOT edit this file directly.\n` +
    `// Edit the source template, then run: node scripts/sync-email-templates.mjs\n\n`
  );
}

// Deno needs explicit .ts on relative imports; Node/Next does not. That is the
// only difference, so it is the only thing we transform.
function toDeno(src, name) {
  const transformed = src.replace(
    /from '(\.\.?\/[^']+?)'/g,
    (full, spec) => (spec.endsWith('.ts') ? full : `from '${spec}.ts'`),
  );
  return banner(name) + transformed;
}

const checkOnly = process.argv.includes('--check');
let stale = false;

for (const file of FILES) {
  const generated = toDeno(readFileSync(join(SRC, file), 'utf8'), file);
  const dstPath = join(DST, file);
  let current = '';
  try {
    current = readFileSync(dstPath, 'utf8');
  } catch {
    current = '';
  }
  if (current === generated) continue;

  if (checkOnly) {
    console.error(`[sync-email-templates] out of sync: ${file}`);
    stale = true;
  } else {
    writeFileSync(dstPath, generated);
    console.log(`[sync-email-templates] wrote ${file}`);
  }
}

if (checkOnly) {
  if (stale) {
    console.error(
      '\nEmail templates are out of sync. Run: node scripts/sync-email-templates.mjs',
    );
    process.exit(1);
  }
  console.log('[sync-email-templates] Deno copies are in sync.');
} else {
  console.log('[sync-email-templates] done.');
}
