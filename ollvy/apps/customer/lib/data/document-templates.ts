export function getDocumentTemplates(serviceSlug: string): DocumentTemplate[] {
  return DOCUMENT_TEMPLATES[serviceSlug] || []
}

export function getRequiredDocumentCount(serviceSlug: string): number {
  const templates = DOCUMENT_TEMPLATES[serviceSlug] || []
  return templates.filter(t => t.isRequired).length
}
